#!/usr/bin/env node
/*
 * The Arch package, written from the release rather than by hand.
 *
 * dota2-mod-manager-bin installs the release's .deb on Arch's own WebKitGTK, GTK and GStreamer.
 * The AppImage carries Ubuntu's WebKitGTK and mixes it with the host's libraries, and on Arch that
 * mix drew a black window or crashed (#761, #797). The binary inside the .deb links the system's
 * copies, so on Arch it runs on Arch's.
 *
 * An AUR package is two files that repeat facts held somewhere else: a version, a checksum, a
 * description and a licence. Kept by hand they go stale one release after somebody stops paying
 * attention, and a stale PKGBUILD fails at the checksum, which reads to the user as "this project
 * is abandoned" rather than "nobody regenerated a file". So both are generated. The checksum comes
 * from the release's SHA256SUMS, the list the release workflow attests through Sigstore.
 *
 *   node tools/release/gen-aur.js              the newest published release
 *   node tools/release/gen-aur.js 4.7.0        a particular one
 *
 * The package leaves a mark beside the app's resources (PACKAGE_MANAGER_MARK in
 * src-tauri/src/main.rs), and the app then leaves its updates to pacman: its own updater would
 * install a .deb over the package.
 *
 * Publishing is a separate act and needs an AUR account: clone ssh://aur@aur.archlinux.org/
 * dota2-mod-manager-bin.git, copy both files in, commit, push. Nothing here touches it.
 */
const fs = require('fs');
const path = require('path');
const https = require('https');

const OUT = path.resolve(__dirname, '../..', 'packaging', 'aur');
const REPO = 'dota2modmanager/dota2-mod-manager';
const PKGNAME = 'dota2-mod-manager-bin';
/** The .deb a release carries (tools/release/tauri-release.mjs DEB). */
const DEB = 'Dota-2-Mod-Manager-amd64.deb';
/**
 * What the binary links or loads, by Arch's package names: WebKitGTK and GTK, the tray's
 * indicator, and GStreamer's plugins, without which WebKit's page process aborts at the first
 * video (crates/mm-core/src/app/media_plugins.rs).
 */
const DEPENDS = ['webkit2gtk-4.1', 'gtk3', 'libayatana-appindicator', 'gst-plugins-base', 'gst-plugins-good', 'hicolor-icon-theme'];

function get(url, depth = 0) {
  return new Promise((resolve, reject) => {
    if (depth > 5) return reject(new Error('too many redirects'));
    https.get(url, { headers: { 'user-agent': 'gen-aur' } }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        res.resume();
        return resolve(get(new URL(res.headers.location, url).toString(), depth + 1));
      }
      if (res.statusCode !== 200) {
        res.resume();
        return reject(new Error(`${res.statusCode} for ${url}`));
      }
      const chunks = [];
      res.on('data', (c) => chunks.push(c));
      res.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    }).on('error', reject);
  });
}

/** The .deb's SHA-256 out of a SHA256SUMS file, or null when the release carries no .deb. */
function debSum(sums) {
  const line = String(sums).split('\n').find((l) => l.trim().endsWith(` ${DEB}`) || l.trim().endsWith(`*${DEB}`));
  const m = line && /^([0-9a-f]{64})\s/.exec(line.trim());
  return m ? m[1] : null;
}

/** Version and the .deb's digest, from the release's own files. */
async function release(version) {
  const base = version
    ? `https://github.com/${REPO}/releases/download/v${version}`
    : `https://github.com/${REPO}/releases/latest/download`;
  const yml = await get(`${base}/latest-linux.yml`);
  const v = /^version:\s*(.+)$/m.exec(yml);
  if (!v) throw new Error(`latest-linux.yml at ${base} is not the shape this expects`);
  const sha256 = debSum(await get(`${base}/SHA256SUMS`));
  if (!sha256) throw new Error(`v${v[1].trim()} carries no ${DEB}: the packages came with a later release`);
  return { version: v[1].trim(), sha256 };
}

const FIELDS = (v) => ({
  pkgname: PKGNAME,
  pkgver: v.version,
  pkgrel: '1',
  pkgdesc: 'Mods for Dota 2 without the file juggling: browse, install, toggle and share cosmetic mods from the open D2PFX catalog',
  arch: 'x86_64',
  url: 'https://dota2modmanager.com',
  license: 'GPL-3.0-or-later',
});

function pkgbuild(v) {
  const f = FIELDS(v);
  return `# Maintainer: TheFleece
#
# Generated by tools/release/gen-aur.js in the upstream repository. Edit that, not this.
# The checksum comes from the release's SHA256SUMS, which the release attests through Sigstore.

pkgname=${f.pkgname}
_appname=dota2-mod-manager
pkgver=${f.pkgver}
pkgrel=${f.pkgrel}
pkgdesc="${f.pkgdesc}"
arch=('${f.arch}')
url="${f.url}"
license=('${f.license}')
depends=(${DEPENDS.map((d) => `'${d}'`).join(' ')})
provides=("\${_appname}")
conflicts=("\${_appname}" 'dota2-mod-manager-appimage')
options=('!strip' '!debug')
source=("\${_appname}-\${pkgver}.deb::https://github.com/${REPO}/releases/download/v\${pkgver}/${DEB}")
sha256sums=('${v.sha256}')

package() {
  # makepkg has unpacked the .deb's ar archive; the files are in data.tar
  bsdtar -xf data.tar.* -C "\${pkgdir}"
  chmod -R go-w "\${pkgdir}"

  # pacman updates this copy, so the app's own updater stays out of it
  local res
  res=$(dirname "$(find "\${pkgdir}/usr/lib" -path '*/app/package.json' | head -n 1)")
  printf 'pacman\\n' > "\${res}/package-manager"
  chmod 644 "\${res}/package-manager"
}
`;
}

/** .SRCINFO is the machine-readable half, and the AUR refuses a push where it disagrees. */
function srcinfo(v) {
  const f = FIELDS(v);
  return `pkgbase = ${f.pkgname}
\tpkgdesc = ${f.pkgdesc}
\tpkgver = ${f.pkgver}
\tpkgrel = ${f.pkgrel}
\turl = ${f.url}
\tarch = ${f.arch}
\tlicense = ${f.license}
${DEPENDS.map((d) => `\tdepends = ${d}`).join('\n')}
\tprovides = dota2-mod-manager
\tconflicts = dota2-mod-manager
\tconflicts = dota2-mod-manager-appimage
\toptions = !strip
\toptions = !debug
\tsource = dota2-mod-manager-${f.pkgver}.deb::https://github.com/${REPO}/releases/download/v${f.pkgver}/${DEB}
\tsha256sums = ${v.sha256}

pkgname = ${f.pkgname}
`;
}

async function main() {
  const asked = process.argv[2] && process.argv[2].replace(/^v/, '');
  const v = await release(asked);

  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, 'PKGBUILD'), pkgbuild(v));
  fs.writeFileSync(path.join(OUT, '.SRCINFO'), srcinfo(v));
  console.log(`packaging/aur written for ${v.version}`);
  console.log(`sha256 ${v.sha256.slice(0, 24)}... (from SHA256SUMS, no download)`);
}

if (require.main === module) {
  main().catch((e) => { console.error(e.message); process.exit(1); });
}

module.exports = { pkgbuild, srcinfo, release, debSum, DEPENDS };
